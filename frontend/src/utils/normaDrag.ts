/** The drag data type a norma card carries while it is dragged: its id. Only folders (and the breadcrumb) accept it. */
export const NORMA_DRAG_TYPE = 'application/x-norma-id';

/** The same for a folder (a card or a row of the tree) being dragged: its id. Folders, the breadcrumb and "Remover da pasta" accept it. */
export const FOLDER_DRAG_TYPE = 'application/x-norma-folder-id';
